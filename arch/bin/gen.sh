#!/usr/bin/env bash
# Regenerate everything under arch/generated/.
#
# The output is committed so the model is readable on GitHub with no tooling
# installed — a reviewer should not have to run a renderer to see what changed.
# CI regenerates and requires an empty diff, so the committed copy cannot rot.
set -euo pipefail
here=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
out=$here/generated

rm -rf "$out/mermaid"
npx --yes likec4@latest gen mmd "$here/model" -o "$out/mermaid" >/dev/null

# One page carrying every view, because .mmd files do not render from a link.
{
  echo "<!-- Generated by arch/bin/gen.sh. Do not edit. -->"
  echo
  echo "# konyklabs — the views"
  echo
  echo "Source: [\`arch/model\`](../model). Regenerate: \`npm --prefix arch run gen\`."
  echo
  for f in index repos gate clock agents trust changeLifecycle roleRun; do
    src=$out/mermaid/$f.mmd
    [ -f "$src" ] || continue
    title=$(sed -n 's/^title: "\(.*\)"$/\1/p' "$src" | head -1)
    echo "## ${title:-$f}"
    echo
    echo '```mermaid'
    sed '/^---$/,/^---$/d' "$src"
    echo '```'
    echo
  done
} >"$out/VIEWS.md"

echo "arch: regenerated $(ls "$out/mermaid" | wc -l | tr -d ' ') diagrams and generated/VIEWS.md"
